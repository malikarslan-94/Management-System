const { chromium, expect } = require('@playwright/test')
const fs = require('node:fs')
const { startPreview } = require('./support/preview.cjs')
;(async () => {
 const config = await startPreview()
 const signin = await fetch(config.base+'/api/sign-in',{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify({user:'admin@example.test',password:'Admin-test-pass-2026'})}).then(r=>r.json())
 const auth = { 'Content-Type':'application/json', Authorization:`Bearer ${signin.token}` }
 const stays = await fetch(config.base+'/api/assignments?status=active',{headers:auth}).then(r=>r.json())
 for (const stay of stays.data) await fetch(config.base+'/api/assignments/'+stay._id,{method:'PUT',headers:auth,body:JSON.stringify({status:'completed',roomAfterCheckout:'available'})})
 const rooms = await fetch(config.base+'/api/rooms',{headers:auth}).then(r=>r.json())
 await fetch(config.base+'/api/rooms/'+rooms.find(r=>r.roomNumber==='101')._id,{method:'PATCH',headers:auth,body:JSON.stringify({status:'available'})})
 const browser = await chromium.launch({ channel: 'chrome', headless: true })
 const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
 page.setDefaultTimeout(15000)
 const runId = Date.now()
 const facilityName = `Community lounge ${runId}`
 const capture = async path => {
  await expect(page.locator('.ReactModalPortal > *')).toHaveCount(0)
  await expect(page.locator('.cw-empty[role="status"]')).toHaveCount(0)
  await page.screenshot({path,fullPage:true,animations:'disabled'})
 }
 const errors = []
 page.on('pageerror', e => errors.push(e.message))
 try {
  await page.goto(config.url + '/sign-in')
  console.log('Sign in fields:', await page.locator('input').evaluateAll(es=>es.map(e=>({name:e.name,placeholder:e.placeholder,type:e.type}))))
  await page.locator('input[name="user"]').fill('admin@example.test')
  await page.locator('input[name="password"]').fill('Admin-test-pass-2026')
  await page.getByRole('button',{name:'Sign In',exact:true}).click()
  await page.waitForURL('**/home')
  await page.goto(config.url + '/check-in-out')
  await expect(page.getByRole('heading', {name:'Check-In / Check-Out',exact:true})).toBeVisible()
  await page.getByRole('button',{name:'New check-in',exact:true}).click()
  await page.getByRole('button',{name:/Ahmed Test/}).click()
  await page.getByRole('button',{name:'Choose room',exact:true}).click()
  await page.getByLabel('Available room').selectOption({label:'101 · single · Floor 1'})
  await page.getByLabel('Expected check-out').fill(new Date(Date.now()+86400000).toISOString().slice(0,10))
  await page.getByRole('button',{name:'Review check-in',exact:true}).click()
  await page.getByRole('button',{name:'Confirm check-in',exact:true}).click()
  await expect(page.getByText('Resident checked in. Room and stay records have been updated.')).toBeVisible()
  fs.mkdirSync('output/feature-validation',{recursive:true})
  await expect(page.getByRole('dialog')).toBeHidden()
  await page.getByRole('tab',{name:'Checked in',exact:true}).click()
  await expect(page.getByRole('button',{name:'Check out',exact:true})).toBeVisible()
  await capture('output/feature-validation/check-in-out-desktop.png')
  await page.getByRole('button',{name:'Check out',exact:true}).click()
  await expect(page.getByRole('radio',{name:'Cleaning',exact:true})).toBeChecked()
  await page.getByRole('button',{name:'Confirm check-out',exact:true}).click()
  await expect(page.getByRole('dialog')).toBeHidden()
  console.log('Checkout flow passed')
  console.log('Check-in flow passed')
  await page.goto(config.url+'/facilities')
  await page.getByRole('button',{name:'Add facility',exact:true}).click()
  await page.getByLabel('Camp', {exact:true}).selectOption(config.campId)
  await page.getByLabel('Type',{exact:true}).selectOption('recreation_center')
  await page.getByLabel('Facility name').fill(facilityName)
  await page.getByLabel('Capacity (people)').fill('48')
  await page.getByLabel('Opening hours',{exact:true}).fill('09:00–21:00')
  await page.getByRole('button',{name:'Save facility',exact:true}).click()
  await expect(page.getByRole('heading',{name:facilityName,exact:true})).toBeVisible()
  await capture('output/feature-validation/facilities-desktop.png')
  console.log('Facility create passed')
  await page.goto(config.url+'/reports')
  await page.getByRole('button',{name:'Generate report',exact:true}).click()
  await expect(page.locator('.cw-report-chart').getByRole('heading',{name:'Room occupancy',exact:true})).toBeVisible()
  const download = page.waitForEvent('download')
  await page.getByRole('button',{name:'Export CSV',exact:true}).click()
  const artifact = await download
  console.log('Report CSV:',artifact.suggestedFilename())
  await capture('output/feature-validation/reports-desktop.png')
  await page.emulateMedia({media:'print'})
  await expect(page.locator('.cw-print-heading')).toBeVisible()
  await capture('output/feature-validation/report-print-preview.png')
  await page.pdf({path:'output/feature-validation/occupancy-report.pdf',format:'A4',printBackground:true})
  await page.emulateMedia({media:'screen'})
  await page.goto(config.url+'/settings-roles')
  await expect(page.getByRole('heading',{name:'Settings & Roles',exact:true})).toBeVisible()
  await page.getByRole('button',{name:'Add user',exact:true}).click()
  await page.getByLabel('Name',{exact:true}).fill('Browser Test Viewer')
  await page.getByLabel('Email',{exact:true}).fill(`browser${runId}@example.test`)
  await page.getByLabel('Role',{exact:true}).selectOption('viewer')
  await page.getByRole('checkbox',{name:'Dammam Camp',exact:true}).check()
  await page.getByLabel('Temporary password',{exact:true}).fill('Temporary-browser-pass')
  await page.getByRole('button',{name:'Review changes',exact:true}).click()
  await page.getByRole('button',{name:'Confirm changes',exact:true}).click()
  await expect(page.getByRole('dialog')).toBeHidden()
  await expect(page.getByText(`browser${runId}@example.test`,{exact:true})).toBeVisible()
  await capture('output/feature-validation/settings-desktop.png')
  await page.getByRole('tab',{name:'Roles',exact:true}).click()
  await expect(page.getByText('Role templates are fixed.',{exact:false})).toBeVisible()
  await page.getByRole('tab',{name:'Preferences',exact:true}).click()
  await page.getByLabel('Organization name',{exact:true}).fill('Browser Test Organization')
  await page.getByRole('button',{name:'Save preferences',exact:true}).click()
  await expect(page.getByText('Organization preferences saved.',{exact:true})).toBeVisible()
  console.log('Users, roles and preferences passed')
  await page.goto(config.url+'/employees?action=add')
  await expect(page.getByRole('heading',{name:'Add New Employee',exact:true})).toBeVisible()
  for (const [name,value] of Object.entries({firstName:'Browser',lastName:'Resident',email:`resident${runId}@example.test`,phone:'0501234567',iqamaNumber:`IQ${runId}`,employeeId:`B${runId}`})) await page.locator(`input[name="${name}"]`).fill(value)
  await page.getByRole('combobox',{name:'Resident camp',exact:true}).click()
  await page.getByRole('option',{name:'Dammam Camp',exact:true}).click()
  await page.getByRole('button',{name:'Create Employee',exact:true}).click()
  await expect(page.getByRole('heading',{name:'Add New Employee',exact:true})).toBeHidden()
  await expect(page.getByText(`B${runId}`,{exact:true})).toBeVisible()
  for(const route of ['rooms','room-assignments','locations-camps']) {
   await page.goto(config.url+'/'+route)
   await expect(page.locator('main, .page-container').first()).toBeVisible()
  }
  await page.getByRole('link',{name:'Admin Panel',exact:true}).click()
  await page.getByRole('button',{name:'Users',exact:true}).click()
  await expect(page.getByRole('heading',{name:'Settings & Roles',exact:true})).toBeVisible()
  console.log('Resident registration and legacy page integration passed')
  for (const [route,name] of [['check-in-out','Check-In / Check-Out'],['facilities','Facilities'],['reports','Reports'],['settings-roles','Settings & Roles']]) {
   await page.setViewportSize({width:390,height:844})
   await page.goto(config.url+'/'+route)
   await expect(page.getByRole('heading',{name,exact:true})).toBeVisible()
   if(route==='check-in-out') await page.getByRole('tab',{name:'History',exact:true}).click()
   const overflow = await page.evaluate(()=>document.documentElement.scrollWidth > innerWidth + 1)
   expect(overflow, `horizontal overflow on ${route}`).toBe(false)
   await capture(`output/feature-validation/${route}-mobile.png`)
  }
  const viewer = await browser.newPage({viewport:{width:1280,height:900}})
  viewer.setDefaultTimeout(15000)
  await viewer.goto(config.url+'/sign-in')
  await viewer.locator('input[name="user"]').fill(`browser${runId}@example.test`)
  await viewer.locator('input[name="password"]').fill('Temporary-browser-pass')
  await viewer.getByRole('button',{name:'Sign In',exact:true}).click()
  await viewer.getByLabel('Temporary password',{exact:true}).fill('Temporary-browser-pass')
  await viewer.getByLabel('New password',{exact:true}).fill('Browser-password-changed')
  await viewer.getByLabel('Confirm password',{exact:true}).fill('Browser-password-changed')
  await viewer.getByRole('button',{name:'Save password',exact:true}).click()
  await expect(viewer.getByRole('heading',{name:'Set your password',exact:true})).toBeHidden()
  await viewer.goto(config.url+'/facilities')
  await expect(viewer.getByRole('heading',{name:'Facilities',exact:true})).toBeVisible()
  await expect(viewer.getByRole('button',{name:'Add facility',exact:true})).toHaveCount(0)
  await viewer.goto(config.url+'/settings-roles')
  await expect(viewer.getByText('Access restricted',{exact:true})).toBeVisible()
  await viewer.close()
  console.log('Mobile layouts and forced password / viewer restrictions passed')
  expect(errors).toEqual([])
  console.log('Settings opened; browser errors:',errors)
 } catch(e) { await page.screenshot({path:'/tmp/campwise-browser-failure.png',fullPage:true}); console.error('PAGE TEXT:',(await page.locator('body').innerText()).slice(-7000)); throw e }
 finally { await browser.close(); await config.stop() }
})().then(()=>{ console.log('Browser suite completed; isolated services stopped.'); process.exit(0) }).catch(e=>{console.error(e);process.exit(1)})
