test('AI chat verifies the account and isolates history for identical client session IDs', async () => {
    const previousUrl = process.env.BACKEND_API_URL
    process.env.BACKEND_API_URL = env.base
    const aiPath = require.resolve('../mcp-server/services/aiService')
    const previousAi = require.cache[aiPath]
    require.cache[aiPath] = { id: aiPath, filename: aiPath, loaded: true, exports: { analyzeIntent: async () => ({ intent: 'unknown', confidence: 0 }) } }
    const express = require('../server/node_modules/express')
    const app = express(); app.use(express.json()); app.use('/mcp/chat', require('../mcp-server/routes/chat'))
    const server = await new Promise(resolve => { const s = app.listen(0, '127.0.0.1', () => resolve(s)) })
    const url = `http://127.0.0.1:${server.address().port}/mcp/chat`
    const headers = token => ({ 'Content-Type': 'application/json', Authorization: `Bearer ${token}` })
    try {
        assert.equal((await fetch(url+'/session/shared_test')).status, 401)
        const sent = await fetch(url, { method: 'POST', headers: headers(f.tokens.camp_manager), body: JSON.stringify({ message: 'Private manager context', sessionId: 'shared_test' }) })
        assert.equal(sent.status, 200)
        const own = await fetch(url+'/session/shared_test', { headers: headers(f.tokens.camp_manager) }).then(r => r.json())
        assert.equal(own.messages.length, 2)
        const other = await fetch(url+'/session/shared_test', { headers: headers(f.tokens.viewer) }).then(r => r.json())
        assert.deepEqual(other.messages, [])
        await fetch(url+'/session/shared_test', { method: 'DELETE', headers: headers(f.tokens.viewer) })
        const retained = await fetch(url+'/session/shared_test', { headers: headers(f.tokens.camp_manager) }).then(r => r.json())
        assert.equal(retained.messages.length, 2)
        assert.equal((await fetch(url, { method: 'POST', headers: headers('invalid'), body: JSON.stringify({ message: 'hello' }) })).status, 401)
    } finally {
        await new Promise(resolve => server.close(resolve))
        if (previousUrl === undefined) delete process.env.BACKEND_API_URL; else process.env.BACKEND_API_URL = previousUrl
        if (previousAi) require.cache[aiPath] = previousAi; else delete require.cache[aiPath]
    }
})
