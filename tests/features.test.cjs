test('simultaneous check-ins cannot double-book a room and all references remain consistent', async () => {
    const attempts = await Promise.all([req('POST', '/assignments', f.stay(0, 0), f.tokens.reception), req('POST', '/assignments', f.stay(0, 1), f.tokens.reception)])
    assert.deepEqual(attempts.map(r => r.status).sort(), [201, 409])
    const stay = attempts.find(r => r.status === 201).data
    assert.equal(await db.model('RoomAssignment').countDocuments({ roomId: f.rooms[0]._id, status: 'active' }), 1)
    assert.equal((await db.model('Room').findById(f.rooms[0]._id)).status, 'occupied')
    const resident = await db.model('Employee').findById(stay.occupantId)
    assert.equal(sid(resident.currentRoomId), sid(f.rooms[0]))
    assert.equal(resident.roomAssignmentHistory.length, 1)
    await expect('PATCH', `/employees/${sid(resident)}`, { currentRoomId: null }, f.token, 400)
    await expect('PATCH', `/employees/${sid(resident)}`, { status: 'Inactive' }, f.token, 409)
    await expect('PATCH', `/rooms/${sid(f.rooms[0])}`, { status: 'available' }, f.token, 409)
    await expect('PUT', `/assignments/${stay._id}`, { status: 'completed' }, f.tokens.reception, 200)
    assert.equal((await db.model('Room').findById(f.rooms[0]._id)).status, 'cleaning')
    const ended = await db.model('Employee').findById(resident._id)
    assert.equal(ended.currentRoomId, null)
    assert.ok(ended.roomAssignmentHistory[0].endDate)
    await expect('PUT', `/assignments/${stay._id}`, { status: 'completed', roomAfterCheckout: 'available' }, f.token, 409)
    assert.equal((await db.model('Room').findById(f.rooms[0]._id)).status, 'cleaning')
})
